def dot_product(v1, v2):
    total = 0
    for i in range(len(v1)):
        if len(v1) == len(v2):
            total += (v1[i] * v2[i])



def matrix_vector_multiplication(m, v):
    total = 0
    if len(m) == len(v):
        for i in range(len(m)):
            for j in range(len(m[0])):
                total += (m[i][j])




        